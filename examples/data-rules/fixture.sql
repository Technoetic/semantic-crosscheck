-- Synthetic rows for the clean-room data rules of examples/data-rules (invented names and values only).
-- Load it as the loader role into the empty source schema sxc_rules (docs/setup-roles.sql with
-- source_schema=sxc_rules), then run `sxc.py build` and `sxc.py data-rules` with examples/data-rules/crosscheck.toml.
-- Each rule of data-rules.toml has planted defects (rows it must find) and near-misses (rows it must not find):
-- exact text (case, a leading or a trailing space), numbers by value (500 against 500.000001, 2 against 2.000),
-- NULL attributes, NULL endpoints, missing parts and inclusive boundaries.
-- Format, relied on by tests/test_data_rules_pg.py: every statement ends with a semicolon at the end of a line,
-- no literal or comment holds a semicolon, and the statements after the line starting with "-- variant:" are the
-- variant (more NULL endpoints and missing references, loaded after the base rows by the mutation tests).

